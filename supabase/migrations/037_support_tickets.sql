-- ============================================================
-- Migration 037: Support tickets, in the console
--
-- /support has had a working-looking form since it shipped: fill it in, wait
-- 1.1 seconds of setTimeout, get "Message sent — we'll get back to you within
-- 2 business days." Nothing was ever sent and nothing was ever stored. Every
-- person who used that form is still waiting for a reply to a message that
-- never existed.
--
-- This is the table behind an actual reply.
--
-- Shape notes:
--
--   * Anonymous submission is allowed. /support is in middleware's PUBLIC_PATHS
--     precisely so someone locked out of their account can still reach a human,
--     and requiring a session would close the door on the people most likely to
--     need it. user_id is therefore nullable and email is not — the email is
--     the only reliable way back to the sender.
--
--   * kind is here from the start, defaulting to 'support', because /report
--     ("Report an issue", Trust & Safety) is the same intake with a different
--     triage path and will land in this table rather than a second one.
--
--   * ref is what the submitter is shown and what they will quote back at you.
--     It is generated by the database, not the route, so it cannot be forged by
--     a client and cannot collide.
--
-- Sealed like error_log (034) and the 033 tables: RLS on with zero policies, so
-- no browser reaches it under any key. The public /api/support route inserts
-- with the service-role key after validating; the Privy-gated
-- /api/admin/support route reads and updates.
-- ============================================================


-- ── Ticket reference ────────────────────────────────────────
--
-- A sequence rather than random hex. A unique constraint over random values
-- means a collision is a failed insert — i.e. the support form breaking for one
-- unlucky person, which is the exact failure this migration exists to end. A
-- sequence cannot collide.
--
-- The tradeoff is that consecutive refs disclose ticket volume to anyone who
-- submits twice and subtracts. That is what Zendesk, Linear and GitHub all do,
-- and the number it leaks is not one worth a reliability cost.
create sequence if not exists public.support_ticket_seq start with 1000;

-- service_role bypasses RLS, not privileges, and nextval() needs USAGE. Granted
-- explicitly rather than relying on Supabase's default-privileges setup, so
-- this migration also applies cleanly to a plain Postgres.
grant usage, select on sequence public.support_ticket_seq to service_role;


create table if not exists public.support_tickets (
  id          uuid primary key default gen_random_uuid(),
  ref         text        not null unique
                default 'SUP-' || lpad(nextval('public.support_ticket_seq')::text, 5, '0'),

  -- 'support' is /support (billing, orders, account). 'report' is /report
  -- (Trust & Safety). Constrained rather than free text so a typo in a route
  -- can't quietly create a third queue nobody is watching.
  kind        text        not null default 'support'
                check (kind in ('support', 'report')),

  -- open      → nobody has picked it up
  -- pending   → replied, waiting on the sender
  -- resolved  → answered, and the answer worked
  -- closed    → no longer actionable (duplicate, spam, abandoned)
  status      text        not null default 'open'
                check (status in ('open', 'pending', 'resolved', 'closed')),

  category    text        not null,
  subject     text        not null,
  message     text        not null,

  -- Where the reply goes. Always collected, even from a signed-in submitter,
  -- because "the address on your account" is frequently the address they have
  -- lost access to.
  email       text        not null,

  -- Free text. Deliberately not a foreign key to orders: people paste order
  -- numbers with typos, from the wrong account, or from an email receipt, and a
  -- constraint here would reject the ticket instead of letting a human sort it
  -- out.
  order_ref   text,

  -- Set only when the submitter had a session. ON DELETE SET NULL keeps the
  -- ticket after an account deletion — the conversation may still be open, and
  -- losing it would erase our own side of the record too.
  user_id     uuid        references auth.users(id) on delete set null,

  -- Severity only applies to 'report'; null for ordinary support.
  severity    text        check (severity in ('low', 'medium', 'high')),

  -- Admin-side. handled_by is the Privy user id of whoever last moved it, not a
  -- profile id — the console authenticates with Privy and has no auth.uid().
  -- Same convention as verification_requests.reviewed_by.
  admin_note  text,
  handled_by  text,
  resolved_at timestamptz,

  -- Drives the rail badge. An admin action, so it lives on the row where a
  -- second admin can see it, not in one person's localStorage.
  seen        boolean     not null default false,

  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- The queue is read newest-first and filtered by status; the badge counts open
-- rows only. The partial index is the badge's whole query.
create index if not exists support_tickets_created_idx on public.support_tickets (created_at desc);
create index if not exists support_tickets_status_idx  on public.support_tickets (status, created_at desc);
create index if not exists support_tickets_open_idx    on public.support_tickets (created_at desc) where status = 'open';
create index if not exists support_tickets_user_idx    on public.support_tickets (user_id) where user_id is not null;

alter table public.support_tickets enable row level security;

-- No policies, on purpose — same posture as error_log.
--
-- A tempting policy is "let users read their own tickets", and it is the wrong
-- thing to add speculatively: nothing in the app renders a ticket history, and
-- carbon_credits already carries one dormant admin policy that reads as working
-- access control while doing nothing. When a "my tickets" screen exists, add
-- the policy then, with the query it is meant to serve in front of you.
--
-- The relevant asymmetry: a support ticket is written by someone who may not be
-- signed in and read by staff. Neither side needs a browser policy.


-- ── Queue counts ────────────────────────────────────────────
--
-- One round trip for the numbers above the table and the number on the rail
-- badge. Doing this as four head-count selects from the route worked but meant
-- the badge and the panel could disagree by a request.
create or replace function public.admin_support_counts()
returns table (
  total     bigint,
  open      bigint,
  pending   bigint,
  resolved  bigint,
  closed    bigint,
  unseen    bigint,
  last_24h  bigint
)
language sql
security definer
set search_path = public, pg_temp
as $$
  select
    count(*)::bigint                                                    as total,
    count(*) filter (where t.status = 'open')::bigint                   as open,
    count(*) filter (where t.status = 'pending')::bigint                as pending,
    count(*) filter (where t.status = 'resolved')::bigint               as resolved,
    count(*) filter (where t.status = 'closed')::bigint                 as closed,
    count(*) filter (where not t.seen)::bigint                          as unseen,
    count(*) filter (where t.created_at >= now() - interval '24 hours')::bigint as last_24h
  from public.support_tickets t;
$$;


-- ── Only the server may call it ─────────────────────────────
--
-- SECURITY DEFINER functions are granted EXECUTE to PUBLIC by default. Without
-- this the anon key could ask an RLS-sealed table how many tickets it holds.
do $$
begin
  execute 'revoke all on function public.admin_support_counts() from public, anon, authenticated';
  execute 'grant execute on function public.admin_support_counts() to service_role';
end $$;
